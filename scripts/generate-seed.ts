/**
 * Writes supabase/seed.sql from the fictional demo fixtures used by the
 * browser-only demo, so both backends start from the same example records.
 *
 *   npm run db:seed:generate
 *
 * Fixture IDs ("glen", "glen-doc-2", …) become stable UUIDs, so running the
 * seed twice does not create duplicates.
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createFixtures } from "../src/data/fixtures";
import {
  businessToRow,
  customerToRow,
  documentToRow,
  itemToRow,
} from "../src/data/rows";

const uuid = (key: string) => {
  const h = createHash("md5").update(`africonnect-demo:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};

const db = createFixtures();
const businesses = db.businesses.map((b) => ({ ...b, id: uuid(b.id) }));
const customers = db.customers.map((c) => ({
  ...c,
  id: uuid(c.id),
  businessId: uuid(c.businessId),
}));
const items = db.items.map((i) => ({
  ...i,
  id: uuid(i.id),
  businessId: uuid(i.businessId),
}));
const documents = db.documents.map((d) => ({
  ...d,
  id: uuid(d.id),
  businessId: uuid(d.businessId),
  customerId: uuid(d.customerId),
  lines: d.lines.map((l) => ({
    ...l,
    referenceId: l.referenceId && uuid(l.referenceId),
  })),
  snapshot: {
    issuer: { ...d.snapshot.issuer, id: uuid(d.snapshot.issuer.id) },
    customer: {
      ...d.snapshot.customer,
      id: uuid(d.snapshot.customer.id),
      businessId: uuid(d.snapshot.customer.businessId),
    },
  },
}));

const stamp = "2026-11-01T08:00:00Z";
const rows = {
  businesses: businesses.map((b) => ({
    ...businessToRow(b),
    created_at: stamp,
    updated_at: stamp,
  })),
  customers: customers.map((c) => ({
    ...customerToRow(c),
    created_at: stamp,
    updated_at: stamp,
  })),
  items: items.map((i) => ({
    ...itemToRow(i),
    created_at: stamp,
    updated_at: stamp,
  })),
  documents: documents.map((d) => ({
    ...documentToRow(d),
    created_by: null,
    created_at: d.updatedAt,
    issued_at: d.status === "issued" ? d.updatedAt : null,
    issued_by: null,
  })),
};

const insert = (table: keyof typeof rows) =>
  `insert into public.${table}
select * from jsonb_populate_recordset(null::public.${table}, $seed$
${JSON.stringify(rows[table], null, 1)}
$seed$::jsonb)
on conflict do nothing;`;

const sql = `-- Fictional demo data for Africonnect Invoicing.
-- Generated by scripts/generate-seed.ts from src/data/fixtures.ts; do not edit by hand.
--
-- Optional. Run it after the schema migration to explore the app with example
-- client businesses. Every name, contact and banking detail here is invented.
-- Running it again does not create duplicates.

begin;

${insert("businesses")}

${insert("customers")}

${insert("items")}

-- Keep the fixture numbers and dates instead of assigning new ones.
alter table public.documents disable trigger documents_prepare;

${insert("documents")}

alter table public.documents enable trigger documents_prepare;

commit;
`;

const out = join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(out, sql);
console.log(
  `Wrote ${out}: ${businesses.length} businesses, ${customers.length} customers, ${items.length} items, ${documents.length} documents.`,
);
